function choice(lesson, title, context, prompt, options, answer, why, clue, difficulty = '中等') {
  const id = `g02-l${String(lesson).padStart(2, '0')}`;
  const n = (counts.get(id) || 0) + 1;
  counts.set(id, n);
  bank.push({ id: `${id}-q${String(n).padStart(2, '0')}`, lessonId: id, title, context, prompt,
    kind: 'choice', options, answer, explanation: why, hints: [hints[lesson], clue, '逐一检查选项是否把不同角色或不同阶段混为一谈。'], difficulty });
}

